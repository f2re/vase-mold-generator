"""UI integration tests. Uses HTTP when VMG_TEST_URL is provided; otherwise Blob fixture."""
import json
import os
from pathlib import Path
from playwright.sync_api import sync_playwright
from browser_fixture import load_app

OUT = Path(os.environ.get('VMG_SCREENSHOT_DIR','artifacts'))
OUT.mkdir(parents=True,exist_ok=True)
URL = os.environ.get('VMG_TEST_URL')
checks = []

def check(name, value):
    assert value, name
    checks.append(name)
    print('PASS',name,flush=True)

with sync_playwright() as pw:
    executable = os.environ.get('VMG_CHROMIUM')
    if not executable and Path('/usr/bin/chromium').exists():
        executable='/usr/bin/chromium'
    browser = pw.chromium.launch(executable_path=executable,headless=True,args=['--no-sandbox'])
    page = browser.new_page(viewport={'width':1440,'height':1040},device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    load_app(page,URL)
    check('initial: 15 meshes, 10 printable',page.evaluate('vmg.model.parts.length===15 && vmg.model.stats.printCount===10'))
    backend=page.evaluate('vmg.viewer.backend')
    check('3D canvas paints non-background pixels',page.evaluate('vmg.viewer.framesDrawn>0'))
    check('all editable fields have accessible labels',page.evaluate('Array.from(document.querySelectorAll("input[type=number]")).every(i=>document.querySelector(`label[for="${i.id}"]`) && i.getAttribute("aria-describedby"))'))
    page.locator('#masterHeight').fill('320')
    check('export blocked immediately on input',page.locator('#exportAll').is_disabled())
    page.wait_for_function('vmg.ready && vmg.model.p.masterHeight===320')
    check('3D and part bounds follow new height',page.evaluate('vmg.viewer.parts.find(p=>p.id==="master").bounds.size[2]===320'))
    page.locator('#masterInnerD').fill('500')
    check('invalid dimensions block export',page.locator('#exportAll').is_disabled() and page.locator('#masterInnerD').get_attribute('aria-invalid')=='true')
    page.locator('#masterInnerD').fill('105')
    page.locator('#masterInnerD').fill('110')
    page.locator('#masterInnerD').fill('100')
    page.wait_for_function('vmg.ready && vmg.model.p.masterInnerD===100')
    check('latest parameter revision wins',page.evaluate('vmg.model.d.co===40'))
    page.locator('[data-part-id="core-bottom"]').click()
    check('bottom selected from tree',page.evaluate('vmg.viewer.selected==="core-bottom"'))
    page.locator('#selection button').first.click()
    check('isolation leaves one visible mesh',page.evaluate('vmg.viewer.parts.filter(p=>vmg.viewer.visible(p)).length===1'))
    with page.expect_download() as download:
        page.locator('#exportPart').click()
    check('individual STL download',download.value.suggested_filename=='core-bottom.stl')
    download.value.save_as(OUT/'core-bottom.stl')
    page.locator('#showAllParts').click()
    page.locator('[data-check-id="shell-1-1"]').uncheck()
    check('visibility toggle removes only chosen wall',page.evaluate('!vmg.viewer.visible(vmg.model.parts.find(p=>p.id==="shell-1-1"))'))
    page.locator('#showAllParts').click()
    page.locator('[data-mode="section"]').click()
    page.wait_for_timeout(350)
    check('section includes master and both silicone volumes',page.evaluate('vmg.viewer.mode==="section" && vmg.viewer.reference.master && vmg.viewer.reference.silicone'))
    page.locator('#sectionRange').fill('25')
    page.locator('#sectionRange').dispatch_event('input')
    check('section plane responds',page.evaluate('vmg.viewer.slice===.25'))
    page.locator('[data-mode="layout"]').click()
    check('layout uses different positions',page.evaluate('new Set(vmg.model.parts.filter(p=>p.printable).map(p=>JSON.stringify(vmg.viewer.shift(p)))).size===10'))
    page.locator('[data-mode="assembly"]').click()
    page.locator('#view3d').focus()
    yaw=page.evaluate('vmg.viewer.yaw')
    page.keyboard.press('ArrowLeft')
    check('keyboard rotation works',page.evaluate('vmg.viewer.yaw')!=yaw)
    page.locator('#reset').click()
    page.wait_for_function('vmg.ready && vmg.model.p.masterHeight===270')
    with page.expect_download() as download:
        page.locator('#exportAll').click()
    download.value.save_as(OUT/'browser-kit.zip')
    check('whole kit ZIP download',download.value.suggested_filename.endswith('_STL.zip'))
    page.locator('#autoSplit').uncheck()
    page.wait_for_function('vmg.ready && !vmg.model.p.autoSplit')
    check('oversize kit cannot export',page.locator('#exportAll').is_disabled())
    page.locator('#reset').click()
    page.wait_for_function('vmg.ready && vmg.model.p.autoSplit')
    with page.expect_download() as download:
        page.locator('#saveProject').click()
    download.value.save_as(OUT/'browser-project.json')
    page.locator('#masterHeight').fill('315')
    page.wait_for_function('vmg.ready && vmg.model.p.masterHeight===315')
    page.locator('#projectFile').set_input_files(OUT/'browser-project.json')
    page.wait_for_function('vmg.ready && vmg.model.p.masterHeight===270')
    check('saved JSON restores the model',True)
    page.locator('#projectFile').set_input_files({'name':'broken.json','mimeType':'application/json','buffer':b'{"masterHeight":null}'})
    check('bad import preserves current valid model',page.evaluate('vmg.ready && vmg.model.p.masterHeight===270'))
    page.locator('#helpToggle').click()
    page.locator('[data-stage="inner"]').click()
    check('second pour stage exposes insert and plate',page.evaluate('vmg.viewer.stage==="inner" && vmg.viewer.parts.filter(p=>p.type==="core"||p.type==="lid").every(p=>vmg.viewer.visible(p))'))
    page.locator('[data-stage="all"]').click()
    page.locator('#helpToggle').click()
    page.locator('#showMaster').uncheck()
    page.locator('#showSilicone').uncheck()
    page.locator('[data-mode="explode"]').click()
    page.locator('[data-camera="iso"]').click()
    page.evaluate('document.querySelector("#toast").hidden=true;document.querySelector(".workspace").scrollTop=0;document.querySelector(".inspector").scrollTop=0;document.querySelector(".parameters").scrollTop=0;window.vmg.viewer.select(null)')
    page.wait_for_timeout(400)
    frames=page.evaluate('vmg.viewer.framesDrawn')
    page.wait_for_timeout(400)
    check('idle preview does not run a permanent render loop',page.evaluate('vmg.viewer.framesDrawn')==frames)
    page.screenshot(path=str(OUT/'desktop.png'),full_page=True)
    page.locator('[data-mode="section"]').click()
    page.locator('#sectionRange').fill('0');page.locator('#sectionRange').dispatch_event('input')
    page.locator('[data-camera="iso"]').click()
    page.wait_for_timeout(350)
    page.screenshot(path=str(OUT/'section.png'),full_page=True)
    check('desktop has no horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1,is_mobile=True,has_touch=True,reduced_motion='reduce')
    mobile.on('pageerror',lambda e:errors.append(str(e)))
    load_app(mobile,URL)
    check('mobile no horizontal overflow',mobile.evaluate('document.documentElement.scrollWidth<=innerWidth'))
    mobile.locator('[data-mode="assembly"]').click()
    check('reduced motion disables spatial transition',mobile.evaluate('vmg.viewer.transitions===null'))
    mobile.locator('[data-mode="explode"]').click()
    mobile.screenshot(path=str(OUT/'mobile.png'),full_page=True)
    check('no uncaught JavaScript errors',not errors)
    result={'checks':len(checks),'passed':checks,'backend':backend,'transport':'HTTP' if URL else 'Blob module fixture','webgl_exercised':backend=='WebGL','errors':errors}
    (OUT/'browser-results.json').write_text(json.dumps(result,ensure_ascii=False,indent=2))
    print(json.dumps(result,ensure_ascii=False),flush=True)
    browser.close()
